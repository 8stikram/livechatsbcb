// Turns the two CSV files of docs/melody-tycoon into src/data/catalog.gen.ts.
// Run by hand: npm run data -w @livechatsbcb/melody
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const docs = join(here, '../../../docs/melody-tycoon');

const parseLine = (line) => {
  const out = [];
  let cur = '';
  let quoted = false;
  for (const ch of line) {
    if (ch === '"') quoted = !quoted;
    else if (ch === ',' && !quoted) { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
};
const readCsv = (file) => {
  const [head, ...rows] = readFileSync(join(docs, file), 'utf8').replace(/\r/g, '').trim().split('\n');
  const keys = parseLine(head);
  return rows.map((r) => Object.fromEntries(parseLine(r).map((v, i) => [keys[i], v])));
};
const list = (v) => (v ? v.split(/[;,]/).map((s) => s.trim()).filter(Boolean) : []);

const artists = readCsv('artistes-echantillon.csv').map((a) => ({
  id: a.id, name: a.nom, country: a.pays, city: a.ville || null,
  genre: a.genre, secondary: list(a.genres_secondaires), tags: list(a.tags),
  gen: +a.gen, potMin: +a.pot_min, potMax: +a.pot_max, fans: +a.fans, hype: +a.hype,
  labelId: a.label_id || null, real: a.reel === 'oui', energyProfile: a.profil_energie,
  sync: +a.sync, merch: +a.merch,
}));
const labels = readCsv('labels.csv').map((l) => ({
  id: l.id, name: l.nom, country: l.pays, real: l.reel === 'oui', size: l.taille,
  tier: +l.palier_jeu, genres: list(l.genres_forts), reputation: +l.reputation, style: l.style_ia,
}));

const labelIds = new Set(labels.map((l) => l.id));
for (const a of artists) {
  if (a.labelId && !labelIds.has(a.labelId)) throw new Error(`unknown label ${a.labelId} for ${a.id}`);
  if (a.potMax < a.potMin) throw new Error(`bad potential for ${a.id}`);
}

const body = `// Generated by tools/build-data.mjs from docs/melody-tycoon/*.csv. Do not edit by hand.
import type { CatalogArtist, CatalogLabel } from '../types.ts';

export const CATALOG_ARTISTS: CatalogArtist[] = ${JSON.stringify(artists, null, 1)};

export const CATALOG_LABELS: CatalogLabel[] = ${JSON.stringify(labels, null, 1)};
`;
writeFileSync(join(here, '../src/data/catalog.gen.ts'), body);
console.log(`${artists.length} artists, ${labels.length} labels`);
